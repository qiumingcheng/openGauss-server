/* Transaction-private flush preparation. No persistent provisional IDs. */
#ifndef OG_LAKE_FLUSH_H
#define OG_LAKE_FLUSH_H
#include "lake_txn_private.h"
#include "lake_file_sdk.h"
struct LakeFlushEnded { int64 position; int64 end_snapshot; };
struct LakeFlushOutput {
    LakeFileCandidate* candidate;
    const char* relative_path;
    int64 footer_bytes;
    int64 row_groups;
    int64* column_bytes;
};
struct LakeFlushFileDeletion {
    LakeDataFile* file;
    LakeFlushOutput output;
    int64 inline_rows;
    int64 rows;
    int64 min_snapshot;
    int64 max_snapshot;
};
struct LakeIdentityFlushGroup {
    LakePartitionTuple key; /* Deep-owned by LakeFlushOperation.context. */
    int64 rows;
    int64 min_birth;
    int64 max_birth;
    int64 min_row_id;
    int64 min_end;
    int64 max_end;
    int64* null_counts;
    char** minima;
    char** maxima;
    LakeFlushEnded* ended;
    int ended_count;
    const char* data_path;
    LakeFlushOutput data;
    LakeFlushOutput deletes;
};
static const int LAKE_IDENTITY_FLUSH_GROUP_LIMIT=2;
/* SQL22 host-only round fence. cutoff remains the fresh per-operation S;
 * birth_cutoff H is fixed across bounded calls until its finite source drains. */
struct LakeFlushRound {
    bool enabled;
    bool existing;
    int64 birth_cutoff;
    int64 eligible_rows;
};
/* Bucket grouping is many-to-one. Preserve the complete original mapping,
 * including already-ended and live versions, before any late-end filtering.
 * 262144 *32 bytes is a hard8MiB per-operation ceiling, independent of work_mem.
 * The existing payload spool continues to spill; this map is only fixed fields. */
static const int LAKE_PARTITION_FLUSH_MAP_LIMIT=262144;
struct LakeFlushVersionPosition {
    int64 row_id;
    int64 birth;
    int64 captured_end; /* -1 means live at prepare S. */
    int32 group;
    int32 position;
};
static_assert(sizeof(LakeFlushVersionPosition)==32,"lake prepared partition map budget changed");
struct LakeFlushOperation {
    MemoryContext context;
    LakeTxnTable* table;
    /* Optional physical source view, owned by context. table retains the
     * complete statement binding/snapshot. This view never becomes a writer. */
    LakeInlineBinding* source_binding;
    SubTransactionId owner_subid;
    int64 cutoff;
    int64 rows;
    int64 min_birth;
    int64 max_birth;
    int64 min_row_id;
    int64 last_row_id;
    int64 last_birth;
    int64 min_end;
    int64 max_end;
    int64* null_counts;
    char** minima;
    char** maxima;
    LakeFlushEnded* ended;
    int ended_count;
    int ended_capacity;
    LakeFlushOutput data;
    LakeFlushOutput deletes;
    int group_count; /*0 retains the existing unpartitioned single-output path. */
    LakeIdentityFlushGroup* groups;
    LakeIdentityPartitionSpec source_partition;
    int version_map_count;
    int version_map_capacity;
    LakeFlushVersionPosition* version_map; /* Bucket specs only; op.context. */
    LakeFlushRound round;
    int file_deletion_count;
    LakeFlushFileDeletion* file_deletions;
};
static inline LakeInlineBinding* LakeFlushBinding(const LakeFlushOperation* op)
{ return op->source_binding ? op->source_binding : op->table->binding; }
extern int LakeFlushDataCandidateCount(const LakeFlushOperation* operation);
/* Paths are validated/generated by the trusted host before this call. The
 * caller fixes one business snapshot and registers MAINTENANCE mode first.
 * Does no catalog writes, snapshot claim, inline deletion or logical ID allocation.
 * Caller retains the operation's parent until transaction/subtransaction end. */
extern LakeFlushOperation* LakePrepareInlineFlush(LakeTxnTable* table,MemoryContext parent,
    const char* dataPath,const char* dataName,const char* deletePath,const char* deleteName);
extern char* LakePrepareFlushDirectory(const LakeInlineBinding* binding,Snapshot snapshot);
struct LakeArrowBuilder;
extern LakeFileCandidate* LakeFlushOpen(const char* path,const OgLakeSdkField* fields,int count,
    int listCount=0,const OgLakeSdkListField* lists=NULL,const LakeInlineBinding* binding=NULL);
extern int32* LakeFlushTypmods(const LakeInlineBinding* binding,int count);
extern void LakeFlushAppend(LakeArrowBuilder* batch,LakeFileCandidate* candidate,Datum* values,bool* nulls);
extern void LakeFlushFinish(LakeFlushOperation* operation,LakeFlushOutput* output,const OgLakeSdkField* fields,int count);
extern void LakeFinishFileOutput(MemoryContext context,const LakeInlineBinding* binding,
    LakeFlushOutput* output,const OgLakeSdkField* fields,int count);
/* Called before transaction adoption; caller owns rollback of the entire op. */
extern void LakePrepareFileDeleteFlush(LakeFlushOperation* op,const char* directory,const char* identity);
extern bool LakeStatsMaintainBounds(Oid type);
extern void LakeObserveColumnBounds(MemoryContext targetContext,Oid type,int32 typmod,
    Datum value,char** minimum,char** maximum);
#endif
